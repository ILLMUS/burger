import { createServerFn } from "@tanstack/react-start";
import { z } from "zod";

const schema = z.object({
  customerId: z.string().uuid().nullable().optional(),
  customerName: z.string().trim().min(2).max(80),
  phone: z.string().trim().min(4).max(30),
  whatsapp: z.string().trim().max(30).nullable().optional(),
  orderType: z.enum(["delivery", "pickup"]),
  address: z.string().trim().max(300).nullable().optional(),
  instructions: z.string().trim().max(500).nullable().optional(),
  items: z.array(z.object({ productId: z.string().uuid(), quantity: z.number().int().min(1).max(50) })).min(1).max(40),
});

/** Creates a guest or customer order. Prices and totals are recomputed server-side. */
export const placeOrder = createServerFn({ method: "POST" })
  .inputValidator((input: unknown) => schema.parse(input))
  .handler(async ({ data }) => {
    const { supabaseAdmin } = await import("@/integrations/supabase/client.server");

    const ids = data.items.map((item) => item.productId);
    const { data: products, error: productError } = await supabaseAdmin
      .from("products")
      .select("id, name, price, available, active")
      .in("id", ids);
    if (productError) throw new Error(productError.message);

    const lines = data.items.map((item) => {
      const product = (products ?? []).find((row) => row.id === item.productId);
      if (!product || !product.available || !product.active) {
        throw new Error("One of the items is no longer available");
      }
      const price = Number(product.price);
      return {
        product_id: product.id,
        product_name: product.name as string,
        quantity: item.quantity,
        price,
        subtotal: price * item.quantity,
      };
    });

    const { data: settings } = await supabaseAdmin.from("store_settings").select("delivery_fee").limit(1).maybeSingle();
    const subtotal = lines.reduce((sum, line) => sum + line.subtotal, 0);
    const deliveryFee = data.orderType === "delivery" ? Number(settings?.delivery_fee ?? 0) : 0;
    const total = subtotal + deliveryFee;

    const { data: order, error } = await supabaseAdmin
      .from("orders")
      .insert({
        // order_number is generated by a database trigger
        customer_id: data.customerId ?? null,
        customer_name: data.customerName,
        phone: data.phone,
        whatsapp: data.whatsapp ?? data.phone,
        order_type: data.orderType,
        address: data.orderType === "delivery" ? (data.address ?? null) : null,
        instructions: data.instructions ?? null,
        subtotal,
        delivery_fee: deliveryFee,
        total,
      } as never)
      .select("id, order_number, subtotal, delivery_fee, total")
      .single();
    if (error) throw new Error(error.message);

    const { error: itemsError } = await supabaseAdmin
      .from("order_items")
      .insert(lines.map((line) => ({ ...line, order_id: order.id })));
    if (itemsError) throw new Error(itemsError.message);

    return order as { id: string; order_number: string; subtotal: number; delivery_fee: number; total: number };
  });
